// Codex and Claude permission policy generation.
//
// Both providers run the same skills, so both receive the same semantic
// authorization categories: ordinary local development is automatic, external
// or destructive effects either prompt or are refused outright. Only the
// syntax differs. `docs/security.md` documents the categories; the contract
// tests prove the two renderings stay in step.
