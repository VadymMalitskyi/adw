export const CLAUDE_ALLOW = ["WebSearch"];

function union(...groups) {
  return [...new Set(groups.flatMap((group) => (Array.isArray(group) ? group : [])))];
}

function claudeToolRules(policy) {
  const result = { allow: [], ask: [], deny: [] };
  for (const entry of effectiveEntries(policy).filter(({ kind }) => kind === "tool")) {
    result[entry.decision].push(`mcp__${entry.mcp_server}__${entry.tool}`);
  }
  return result;
}

export function mergeClaudeSettings(source = "", policy = defaultPermissionPolicy()) {
  let settings = {};
  if (source.trim()) {
    try { settings = JSON.parse(source); }
    catch (error) { throw new ContractError(`cannot merge .claude/settings.json: ${error.message}`); }
  }
  if (!settings || typeof settings !== "object" || Array.isArray(settings)) throw new ContractError(".claude/settings.json must contain one JSON object");
  const permissions = settings.permissions && typeof settings.permissions === "object" && !Array.isArray(settings.permissions) ? { ...settings.permissions } : {};
  if (permissions.defaultMode && permissions.defaultMode !== "acceptEdits") throw new ContractError(`.claude/settings.json permissions.defaultMode=${JSON.stringify(permissions.defaultMode)} conflicts with ${PERMISSION_PROFILE}`);
  if (permissions.allow !== undefined && !Array.isArray(permissions.allow)) throw new ContractError(".claude/settings.json permissions.allow must be an array");
  if ((permissions.allow ?? []).some((rule) => typeof rule !== "string")) throw new ContractError(".claude/settings.json permissions.allow entries must be strings");
  if ((permissions.allow ?? []).some((rule) => /^mcp__\*$/.test(rule))) throw new ContractError(".claude/settings.json contains a broad MCP allow rule that conflicts with managed external-write review");
  const bashAllows = (permissions.allow ?? []).filter((rule) => typeof rule === "string" && /^Bash(?:\(|$)/.test(rule));
  if (bashAllows.length > 0) throw new ContractError(`.claude/settings.json contains Bash allow rules that ${PERMISSION_PROFILE} cannot preserve safely; review and remove them explicitly: ${bashAllows.join(", ")}`);
  permissions.defaultMode = "acceptEdits";
  permissions.disableBypassPermissionsMode = "disable";
  const existingAllows = (permissions.allow ?? []).filter((rule) => typeof rule === "string");
  const toolRules = claudeToolRules(policy);
  permissions.allow = union(existingAllows, CLAUDE_ALLOW, toolRules.allow);
  permissions.ask = union(permissions.ask, CLAUDE_ASK, toolRules.ask);
  permissions.deny = union(permissions.deny, CLAUDE_DENY, toolRules.deny);
  const sandbox = settings.sandbox && typeof settings.sandbox === "object" && !Array.isArray(settings.sandbox) ? { ...settings.sandbox } : {};
  for (const key of ["enabled", "failIfUnavailable", "autoAllowBashIfSandboxed"]) if (sandbox[key] === false) throw new ContractError(`.claude/settings.json sandbox.${key}=false conflicts with ${PERMISSION_PROFILE}`);
  if (sandbox.allowUnsandboxedCommands === true) throw new ContractError(`.claude/settings.json sandbox.allowUnsandboxedCommands=true conflicts with ${PERMISSION_PROFILE}`);
  if (sandbox.filesystem?.disabled === true || sandbox.enableWeakerNestedSandbox === true || (Array.isArray(sandbox.excludedCommands) && sandbox.excludedCommands.length > 0)) throw new ContractError(`.claude/settings.json weakens the ${PERMISSION_PROFILE} sandbox`);
  Object.assign(sandbox, { enabled: true, failIfUnavailable: true, autoAllowBashIfSandboxed: true, allowUnsandboxedCommands: false });
  return `${JSON.stringify({ $schema: settings.$schema ?? "https://json.schemastore.org/claude-code-settings.json", ...settings, permissions, sandbox }, null, 2)}\n`;
}

// The container-owned Claude policy: the project settings above plus the
// egress allowlist and the root-installed effect-classification hook.
export function managedClaudeSettings({ allowedDomains = [], webAccess = "public-pages", policy = defaultPermissionPolicy() } = {}) {
  if (!["hosted-only", "public-pages"].includes(webAccess)) throw new ContractError(`unsupported web access profile: ${webAccess}`);
  const settings = JSON.parse(mergeClaudeSettings("", policy));
  // Bubblewrap cannot create the Linux user namespace its nested sandbox
  // needs here: the managed image deliberately never grants CAP_SYS_ADMIN or
  // apparmor=unconfined (see execution:hardening), so unshare(CLONE_NEWUSER)
  // is rejected outright and every bwrap invocation fails before it can do
  // anything, sandboxed or not. failIfUnavailable/allowUnsandboxedCommands do
  // not paper over that: they cover a missing sandbox dependency and a
  // command the sandbox denies, not the sandbox failing to launch, and
  // Claude Code's own auto-mode classifier treats the resulting
  // dangerouslyDisableSandbox retry as an escalation that needs approval no
  // hook here can grant (this profile deliberately disables
  // bypassPermissions) -- so left at the default, every single Bash call
  // dead-ends. There is no bwrap workaround for a container hardened this
  // way (verified directly: even a bare `bwrap --unshare-user` fails the
  // same way, so enableWeakerNestedSandbox's /proc bind-mount trick, which
  // addresses a later step, never gets reached either). The nested sandbox
  // is turned off entirely instead; the outer container -- non-root, dropped
  // capabilities, fail-closed egress, this same ask/deny policy enforced by
  // the PreToolUse hook below -- is the isolation boundary here. Outside this
  // container (a bare host with no other boundary), mergeClaudeSettings still
  // fails closed by default.
  settings.sandbox.enabled = false;
  settings.sandbox.network = {
    allowedDomains: [...new Set(allowedDomains)].sort(),
    strictAllowlist: true,
    ...(webAccess === "hosted-only" ? { allowManagedDomainsOnly: true } : {}),
  };
  settings.hooks = {
    PreToolUse: [
      { matcher: "Bash", hooks: [{ type: "command", command: "/usr/local/bin/adw-claude-permission-hook" }] },
      { matcher: "^mcp__.*$", hooks: [{ type: "command", command: "/usr/local/bin/adw-claude-permission-hook" }] },
    ],
  };
  return `${JSON.stringify(settings, null, 2)}\n`;
}

export const PERMISSION_FILES = Object.freeze([".codex/config.toml", ".codex/rules/adw.rules", ".claude/settings.json"]);

// Both providers share one skill tree, so every project gets both policies.
export function permissionProjectFiles(readExisting = () => "", { repairManagedRules = false, policy = defaultPermissionPolicy() } = {}) {
  const rules = renderCodexRules(policy);
  const existingRules = readExisting(".codex/rules/adw.rules");
  if (!repairManagedRules && existingRules && existingRules !== rules) throw new ContractError(".codex/rules/adw.rules differs from the ADW managed-development policy");
  return [
    { path: ".codex/config.toml", content: mergeCodexConfig(readExisting(".codex/config.toml"), policy) },
    { path: ".codex/rules/adw.rules", content: rules },
    { path: ".claude/settings.json", content: mergeClaudeSettings(readExisting(".claude/settings.json"), policy) },
  ];
}
